-- Yanked recall database — migration 0001 (applied by scripts/db/migrate.mjs).
--
-- Five layers, each with one job, kept in separate tables so none of them can
-- quietly become another:
--
--   raw_records     what each agency sent, AS RECEIVED, append-only and
--                   versioned. Never edited, never slimmed. A record whose
--                   payload is byte-for-byte the same as last time only has
--                   its last_seen moved; a changed payload is a new row.
--   recalls         canonical: one row per recall, produced from the newest
--                   raw version by the app's existing normalizers.
--   recall_changes  history of the fields a reader cares about changing
--                   (status, states, coverage, classification, ...).
--   recall_index    DERIVED from recalls by a pure function (category, reason,
--                   search text), stamped with CLASSIFIER_VERSION. Bumping the
--                   version re-derives every row without refetching anything.
--   published       the manifest and chunk bodies /api/data serves verbatim.
--
-- sync_runs records every run, one row per source.
--
-- Portable between Postgres 14+ (Neon, Supabase) and PGlite. Everything is
-- `if not exists`, so re-applying it is harmless. Do not edit this file once
-- it has been applied anywhere: add db/migrations/NNNN_name.sql instead.

create table if not exists sync_runs (
  id                    bigserial primary key,
  source                text        not null,          -- fda | fsis | cpsc | announcements
  mode                  text        not null,          -- full | incremental | snapshot
  started_at            timestamptz not null,
  finished_at           timestamptz,
  ok                    boolean,
  fetched               integer     not null default 0,
  raw_new               integer     not null default 0,
  inserted              integer     not null default 0,
  updated               integer     not null default 0,
  unchanged             integer     not null default 0,
  upstream_last_updated date,                          -- openFDA meta.last_updated
  newest_posted         date,
  error                 text,
  dry_run               boolean     not null default false,
  details               jsonb       not null default '{}'::jsonb
);
create index if not exists sync_runs_source_started on sync_runs (source, started_at desc);

create table if not exists raw_records (
  id            bigserial primary key,
  source        text        not null,                  -- fda | fsis | cpsc | announcements
  source_key    text        not null,                  -- the recall id this payload is for
  format        text        not null,                  -- openfda:food | fsis-api | cpsc-api | rss-item | *-snapshot | index-record
  payload       jsonb       not null,
  payload_hash  text        not null,                  -- sha256 of the payload (sorted keys)
  first_seen    timestamptz not null,
  last_seen     timestamptz not null,
  fetch_run_id  bigint      references sync_runs (id),  -- the run that first stored this version
  last_run_id   bigint      references sync_runs (id),  -- the run that last saw it (newest version = highest)
  unique (source, source_key, payload_hash)
);
create index if not exists raw_records_latest on raw_records (source, source_key, last_run_id desc);

create table if not exists recalls (
  id             text primary key,                     -- the app's id scheme (fdaId, fsis-…, cpsc-…, fda-ann-…)
  feed           text        not null,                 -- fda | fsis | cpsc | announcements
  source         text        not null,                 -- FDA Food | FDA Drug | FDA Device | USDA FSIS | CPSC | FDA announcement
  source_key     text        not null,
  product        text        not null default '',
  firm           text        not null default '',
  reason         text        not null default '',
  classification text        not null default '',
  severity       text        not null default 'med',
  status         text        not null check (status in ('active', 'ended', 'announced')),
  distribution   text        not null default '',
  states         text[]      not null default '{}',
  coverage       text        not null default 'unstated',
  initiated      date,                                 -- IndexRecord.date
  posted         date,                                 -- FDA report date
  ended          date,                                 -- IndexRecord.endDate
  url            text        not null default '',
  upcs           text[]      not null default '{}',
  image          text,                                 -- the agency's own product photo (CPSC only), validated
  announcement   boolean     not null default false,
  hints          jsonb       not null default '{}'::jsonb, -- classifier inputs a row cannot hold (announcements)
  raw_hash       text        not null,                 -- payload_hash of the raw version that produced this row
  content_hash   text        not null,
  first_seen     timestamptz not null,
  updated_at     timestamptz not null
);
create index if not exists recalls_feed on recalls (feed);
create index if not exists recalls_news_day on recalls ((greatest(posted, initiated)));

create table if not exists recall_changes (
  id          bigserial primary key,
  recall_id   text        not null references recalls (id),
  at          timestamptz not null,
  field       text        not null,
  old         jsonb,
  new         jsonb,
  sync_run_id bigint      references sync_runs (id)
);
create index if not exists recall_changes_recall on recall_changes (recall_id, at);

create table if not exists recall_index (
  recall_id          text    not null references recalls (id),
  classifier_version integer not null,
  category           text    not null,
  reason_key         text    not null,
  search_text        text    not null,
  news_day           date,
  source_hash        text    not null,                 -- recalls.content_hash it was derived from
  derived_at         timestamptz not null,
  primary key (recall_id, classifier_version)
);

create table if not exists published (
  key        text primary key,                         -- 'manifest' | 'chunk:<key>'
  hash       text        not null,
  body       text        not null,                     -- served verbatim
  bytes      integer     not null,
  updated_at timestamptz not null
);
